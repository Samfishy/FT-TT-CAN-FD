void HAL_TIM_OC_DelayElapsedCallback(TIM_HandleTypeDef *htim)
{
    if(htim->Channel == HAL_TIM_ACTIVE_CHANNEL_2)  // BC boundary (10 ms)
    {
        i1++;

        // Update BC counter
        if(bc_norm < 3)
        {
            bc_norm++;
        }
        else
        {
            HAL_GPIO_TogglePin(GPIOC, GPIO_PIN_0);
            bc_norm = 0;
        }
        debug1[i1] = bc_norm;

        // Reset message pointer for new BC
        mt_pointer_norm = 0;

        // Get first message timing for new BC
        if(mode_switch == 0)
        {
            td_norm = canfd_S_LO[bc_norm][0].Td;
            ta_norm = canfd_S_LO[bc_norm][0].Ta;
        }
        else
        {
            td_norm = canfd_S_HI[bc_norm][0].Td;
            ta_norm = canfd_S_HI[bc_norm][0].Ta;
        }

        // ✅ FIX: Schedule first message of new BC
        __HAL_TIM_SET_COMPARE(htim, TIM_CHANNEL_3, td_norm);
        __HAL_TIM_SET_COMPARE(htim, TIM_CHANNEL_4, ta_norm + 25);
    }

    else if(htim->Channel == HAL_TIM_ACTIVE_CHANNEL_3)  // Message slot
    {
        if(mt_pointer_norm < 13)  // ✅ Within bounds
        {
            // Get message parameters
            if(mode_switch == 0)
            {
                td_norm   = canfd_S_LO[bc_norm][mt_pointer_norm].Td;
                ta_norm   = canfd_S_LO[bc_norm][mt_pointer_norm].Ta;
                mess_norm = canfd_S_LO[bc_norm][mt_pointer_norm].id;
            }
            else
            {
                td_norm   = canfd_S_HI[bc_norm][mt_pointer_norm].Td;
                ta_norm   = canfd_S_HI[bc_norm][mt_pointer_norm].Ta;
                mess_norm = canfd_S_HI[bc_norm][mt_pointer_norm].id;
            }

            // Debug logging
            debug[0][i0] = td_norm;
            debug[1][i0] = ta_norm;
            debug[2][i0] = mt_pointer_norm;

            // Transmit if TX slot
            if(can_test_matrix[mess_norm].rx_tx == 1)  // ✅ Explicit check
            {
                TTCAN_tx();
            }

            // ✅ FIX: Update CCR BEFORE incrementing pointer
            mt_pointer_norm++;

            if(mt_pointer_norm < 13)  // ✅ Check next message exists
            {
                if(mode_switch == 0)
                {
                    TIM1->CCR3 = (uint16_t)canfd_S_LO[bc_norm][mt_pointer_norm].Td;
                    TIM1->CCR4 = (uint16_t)(canfd_S_LO[bc_norm][mt_pointer_norm].Ta + 25);
                }
                else
                {
                    TIM1->CCR3 = (uint16_t)canfd_S_HI[bc_norm][mt_pointer_norm].Td;
                    TIM1->CCR4 = (uint16_t)(canfd_S_HI[bc_norm][mt_pointer_norm].Ta + 25);
                }
            }
            // else: Last message - CHANNEL_2 will restart at BC boundary

            i0++;
        }
    }

    else if(htim->Channel == HAL_TIM_ACTIVE_CHANNEL_4)  // TA check window
    {
        if(send_cmpt == 1)
        {
            Tx_can.DataLength = FDCAN_DLC_BYTES_5;
        }
    }
}





